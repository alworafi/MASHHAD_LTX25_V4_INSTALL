  rm -rf -- "$LOCAL_DIRECT_REPO"
  tar -xzf "$DIRECT_CACHE" -C "$LOCAL_RUNTIME_PARENT"
  validate_direct_runtime "$LOCAL_DIRECT_REPO"
}
