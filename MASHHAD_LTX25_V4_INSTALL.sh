#!/usr/bin/env bash
# Mashhad LTX25 V8: correct BF16 Dev + HIKARI LoRA workflow and sampling.
set -Eeuo pipefail
VERSION='MASHHAD_LTX25_V8_BF16_DEV_LORA_20261016'
export MASHHAD_ROOT="${MASHHAD_ROOT:-/workspace/LTX25}"
ROOT="$MASHHAD_ROOT"
export MASHHAD_START_TS="${MASHHAD_START_TS:-$(date +%s)}"
RUNTIME="$ROOT/.runtime"
LOCAL_RUNTIME_PARENT="${MASHHAD_LOCAL_RUNTIME_PARENT:-/opt/mashhad-ltx25}"
LOCAL_DIRECT_REPO="$LOCAL_RUNTIME_PARENT/LTX-2"
DIRECT_CACHE_DIR="$ROOT/runtime-cache"
DIRECT_CACHE="$DIRECT_CACHE_DIR/direct-py312-torch291-cu128.tar.gz"
DIRECT_CACHE_SHA="$DIRECT_CACHE.sha256"
LOCAL_COMFY_DIR="$LOCAL_RUNTIME_PARENT/ComfyUI"
COMFY_CACHE_DIR="$ROOT/runtime-cache"
COMFY_CACHE="$COMFY_CACHE_DIR/comfyui-py312-torch291-cu128.tar.gz"
COMFY_CACHE_SHA="$COMFY_CACHE.sha256"
TOOLS_VENV="$LOCAL_RUNTIME_PARENT/tools-venv"
HIKARI_LORA_NAME='lora_weights_step_00800.safetensors'
HIKARI_LORA_URL='https://github.com/alworafi/Mashhad-LoRAs/releases/download/hikari-v1/lora_weights_step_00800.safetensors'
HIKARI_LORA_SHA256='3e4ad00e8e33287c81ea0e8f4dc39e9ef19208912c2102c406e1a2919c56f80e'
HIKARI_LORA_SIZE='201431592'
elapsed() { local sec=$(($(date +%s)-MASHHAD_START_TS)); printf '%02d:%02d:%02d' "$((sec/3600))" "$(((sec%3600)/60))" "$((sec%60))"; }
format_duration() { local sec="${1:-0}"; printf '%02d:%02d:%02d' "$((sec/3600))" "$(((sec%3600)/60))" "$((sec%60))"; }
fail() { echo "ERROR: $*" >&2; exit 2; }
PREPARE_MODE="${MASHHAD_PREPARE_ENGINES:-direct,comfyui}"
PREPARE_MODE="${PREPARE_MODE,,}"
PREPARE_MODE="${PREPARE_MODE// /}"
case "$PREPARE_MODE" in
  direct) WANT_DIRECT=1; WANT_COMFYUI=0 ;;
  comfyui) WANT_DIRECT=0; WANT_COMFYUI=1 ;;
  both|direct,comfyui|comfyui,direct) PREPARE_MODE='direct,comfyui'; WANT_DIRECT=1; WANT_COMFYUI=1 ;;
  *) fail "MASHHAD_PREPARE_ENGINES must be direct, comfyui, or direct,comfyui (received: $PREPARE_MODE)." ;;
esac
DEFAULT_ENGINE="${MASHHAD_DEFAULT_ENGINE:-direct}"
DEFAULT_ENGINE="${DEFAULT_ENGINE,,}"
[[ "$DEFAULT_ENGINE" == direct || "$DEFAULT_ENGINE" == comfyui ]] || fail 'MASHHAD_DEFAULT_ENGINE must be direct or comfyui.'
if [[ "$DEFAULT_ENGINE" == direct && "$WANT_DIRECT" != 1 ]]; then DEFAULT_ENGINE='comfyui'; fi
if [[ "$DEFAULT_ENGINE" == comfyui && "$WANT_COMFYUI" != 1 ]]; then DEFAULT_ENGINE='direct'; fi
COMFY_AUTO_START="${MASHHAD_COMFYUI_AUTO_START:-0}"
[[ "$EUID" == 0 ]] || fail 'Run as root inside the RunPod container.'
command -v findmnt >/dev/null || fail 'Use the documented RunPod PyTorch Ubuntu image (findmnt missing).'
SRC=$(findmnt -T /workspace -n -o SOURCE 2>/dev/null || true)
FSTYPE=$(findmnt -T /workspace -n -o FSTYPE 2>/dev/null || true)
[[ -n "$SRC" && "$FSTYPE" != overlay && "$FSTYPE" != tmpfs ]] || fail '/workspace must be on mounted persistent storage. Attach your Network Volume first.'
mkdir -p "$ROOT/logs" "$ROOT/models/ltx-2.5" "$RUNTIME"
exec 9>"$ROOT/.mashhad-install.lock"
flock -n 9 || fail 'Another Mashhad install/start process is using this volume.'
rm -f -- "$ROOT/.MASHHAD_READY_V4"
LOG="$ROOT/logs/install_$(date +%Y%m%d_%H%M%S).log"
exec > >(tee -a "$LOG") 2>&1
printf '%s\n' "$LOG" > "$ROOT/logs/current_install_log"
printf '%s\n' "$MASHHAD_START_TS" > "$ROOT/logs/current_start_ts"
trap 'rc=$?; echo "FAILED at line $LINENO; exit=$rc; elapsed=$(elapsed); log=$LOG"; exit "$rc"' ERR
echo "=== $VERSION ==="
echo "Start: $(date -Is) | persistent filesystem: $SRC ($FSTYPE)"
echo "Requested engines: $PREPARE_MODE | default: $DEFAULT_ENGINE | ComfyUI auto-start: $COMFY_AUTO_START"
echo "Training preparation: ${MASHHAD_INSTALL_TRAINING:-0} (official Dev/Gemma BF16 weights are selected only when enabled)"
echo 'No MSR is installed. Existing unrelated custom nodes are preserved.'
[[ -n "${HF_TOKEN:-}" ]] && export HF_TOKEN="$(printf '%s' "$HF_TOKEN" | tr -d '\r\n')"
echo '[1/7] System runtime packages...'
PACKAGES=(git git-lfs ffmpeg curl ca-certificates build-essential python3 python3-venv python3-pip libgl1 libglib2.0-0)
MISSING=()
for package in "${PACKAGES[@]}"; do
  [[ "$(dpkg-query -W -f='${Status}' "$package" 2>/dev/null || true)" == 'install ok installed' ]] || MISSING+=("$package")
done
if ((${#MISSING[@]})); then
  apt-get update
  DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends "${MISSING[@]}"
  apt-get clean
fi
echo '[2/7] Persistent Python and packaged helpers...'
mkdir -p "$RUNTIME"/{bin,python} "$ROOT/mashhad" "$LOCAL_RUNTIME_PARENT/.uv-cache"
if [[ ! -x "$RUNTIME/bin/uv" ]]; then
  curl -fLsS --retry 4 https://astral.sh/uv/install.sh -o /tmp/mashhad-uv-install.sh
  env UV_UNMANAGED_INSTALL="$RUNTIME/bin" sh /tmp/mashhad-uv-install.sh
fi
export PATH="$RUNTIME/bin:$PATH"
export UV_PYTHON_INSTALL_DIR="$LOCAL_RUNTIME_PARENT/python"
export UV_CACHE_DIR="$LOCAL_RUNTIME_PARENT/.uv-cache"
# Keep uv's many small cache files on the Pod-local disk too. The finished
# runtime is archived as one large file on the Network Volume after validation.
export UV_LINK_MODE=hardlink
if python3 -c 'import sys; assert sys.version_info[:2] == (3, 12)' >/dev/null 2>&1; then
  PYTHON_312="$(command -v python3)"
else
  uv python install 3.12
  PYTHON_312=3.12
fi
# Embedded helpers, model manifest and both workflows. No separate GitHub downloads.
base64 -d <<'MASHHAD_PAYLOAD' | tar -xz -C "$ROOT/mashhad"
