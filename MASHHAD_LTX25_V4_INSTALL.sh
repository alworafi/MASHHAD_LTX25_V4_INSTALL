    for _ in {1..20}; do
      kill -0 "$MODEL_PID" 2>/dev/null || break
      sleep 1
    done
    if kill -0 "$MODEL_PID" 2>/dev/null; then
      kill -KILL "$MODEL_PID" 2>/dev/null || true
    fi
  fi
  wait "$MODEL_PID" 2>/dev/null || true
  MODEL_PID=''
}
